// Permanent model IDs from the Beta 4 firmware changelog and release notes.
const fresh = new Set([28, 51, 53, 56, 67, 71, 76, 92, 93, 94, 95, 97, 98, 99]);

export function modelInfo(id) {
  if (id === 59) return 'Starts fresh when reselected, with about 4 ms of silence.';
  return fresh.has(id) ? 'Starts fresh when reselected.' : '';
}
